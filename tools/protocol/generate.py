def generate(model: Model) -> dict[Path, str]:
    """Every file the generator owns, by path."""
    files: dict[Path, str] = {}
    descriptions = {r.name: (r.description, r.since) for r in model.requests}
    event_descriptions = {e.name: (e.description, e.since) for e in model.events}

    files[GENERATED / "Responses.g.cs"] = emit_dtos(model, "OBSStudioClient.Responses", pm.response_dtos(model), "response")
    files[GENERATED / "EventArgs.g.cs"] = emit_dtos(model, "OBSStudioClient.Events", pm.event_dtos(model), "event")
    files[GENERATED / "RequestResponseMessage.g.cs"] = emit_response_registry(model)
    files[GENERATED / "EventMessage.g.cs"] = emit_event_registry(model)
    files[GENERATED / "ObsClient.Events.g.cs"] = emit_events(model)
    files[GENERATED / "RequestType.g.cs"] = emit_enum(
        model, "RequestType", ordinal_members(model, "RequestType", descriptions),
        "The requests that obs-websocket knows.", "JsonStringEnumConverter")
    files[GENERATED / "EventType.g.cs"] = emit_enum(
        model, "EventType", ordinal_members(model, "EventType", event_descriptions),
        "The events that obs-websocket knows. Unknown stands for an event type this version of the client does not know.", "EventTypeConverter")
    for category in CATEGORY_ORDER + sorted({r.category for r in model.requests} - set(CATEGORY_ORDER)):
        requests = [r for r in model.generated_requests() if r.category == category]
        if requests:
            title = CATEGORY_TITLES.get(category, category.title()).replace(" ", "")
            files[GENERATED / f"Requests.{title}.g.cs"] = emit_requests(model, requests)
    files[SNAPSHOT] = json.dumps(build_snapshot(model), indent=2) + "\n"
    return files


def existing_generated_files() -> set[Path]:
    return set(GENERATED.glob("*.g.cs")) if GENERATED.is_dir() else set()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the committed files differ from what would be generated")
    parser.add_argument("--output-root", help="write below this directory instead of the repository (for experiments)")
    args = parser.parse_args(argv)

    try:
        model = Model.load()
        missing = unassigned_ordinals(model)
        if missing:
            if args.check:
                for enum, names in missing.items():
                    print(f"::error::{enum} has no ordinal for {', '.join(names)}; run tools/protocol/generate.py and commit overlay.toml")
                return 1
            assign_ordinals(model, missing)
            model = Model.load()
        files = generate(model)
    except ModelError as error:
        print(f"::error::{error}")
        return 1

    if args.output_root:
        root = Path(args.output_root)
        files = {root / path.relative_to(pm.ROOT): content for path, content in files.items()}

    if args.check:
        problems = []
        for path, content in sorted(files.items()):
            if not path.exists():
                problems.append(f"{path.relative_to(pm.ROOT)} is missing")
            elif path.read_bytes() != content.encode("utf-8"):
                problems.append(f"{path.relative_to(pm.ROOT)} is not what the generator produces")
        stale = sorted(existing_generated_files() - set(files))
        problems += [f"{path.relative_to(pm.ROOT)} is no longer generated" for path in stale]
        if problems:
            for problem in problems:
                print(f"::error::{problem}")
            print("Run `python tools/protocol/generate.py` and commit the result.")
            return 1
        print(f"The {len(files)} generated files are up to date.")
        return 0

    for path, content in sorted(files.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode("utf-8"))
    if not args.output_root:
        for path in sorted(existing_generated_files() - set(files)):
            path.unlink()
            print(f"removed {path.relative_to(pm.ROOT)} (no longer generated)")
    print(f"Wrote {len(files)} files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
