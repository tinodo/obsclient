def evaluate_enum_value(value, resolved):
    """Turns an upstream enumValue (an int, "-1", "(1 << 4)" or "(A | B)") into an int; anything else stays text."""
    if isinstance(value, int):
        return value
    text = str(value).strip()
    if re.fullmatch(r"-?\d+", text):
        return int(text)
    shift = re.fullmatch(r"\(?\s*(\d+)\s*<<\s*(\d+)\s*\)?", text)
    if shift:
        return int(shift.group(1)) << int(shift.group(2))
    if "|" in text:
        total = 0
        for part in text.strip("() ").split("|"):
            name = part.strip()
            if name not in resolved or not isinstance(resolved[name], int):
                return text
            total |= resolved[name]
        return total
    return text


def snapshot_field(f: pm.Field) -> dict:
    result = {"name": f.name, "type": f.vtype}
    if f.optional:
        result["optional"] = True
    return result


def build_snapshot(model: Model) -> dict:
    enums = {}
    for enum in sorted(model.enums, key=lambda e: e["enumType"]):
        resolved = {}
        for identifier in enum["enumIdentifiers"]:
            resolved[identifier["enumIdentifier"]] = evaluate_enum_value(identifier.get("enumValue"), resolved)
        enums[enum["enumType"]] = resolved
    return {
        "obsWebSocketVersion": model.version,
        "source": f"https://github.com/obsproject/obs-websocket/blob/{model.version}/docs/generated/protocol.json",
        "requests": {
            r.name: {"request": [snapshot_field(f) for f in r.request_fields], "response": [snapshot_field(f) for f in r.response_fields]}
            for r in sorted(model.requests, key=lambda r: r.name)
        },
        "events": {e.name: [snapshot_field(f) for f in e.fields] for e in sorted(model.events, key=lambda e: e.name)},
        "enums": enums,
    }


