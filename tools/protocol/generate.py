"""Generates the protocol-derived parts of OBSClient from obs-websocket's protocol.json and tools/protocol/overlay.toml.

    python tools/protocol/generate.py            # write the generated files
    python tools/protocol/generate.py --check    # fail if the committed files are not what the generator produces

The generated C# is committed under OBSClient/Generated and compiled into OBSClient.dll like any other source. The
protocol definition, the overlay and this generator are inputs of the build: none of them is part of the package
(tools/verify-package.py checks that in CI). Only the Python standard library is used.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import protocol_model as pm  # noqa: E402
from protocol_model import Dto, Model, ModelError  # noqa: E402

GENERATED = pm.ROOT / "OBSClient" / "Generated"
SNAPSHOT = pm.ROOT / "OBSClient.Tests" / "Protocol" / "protocol.schema.json"

HEADER = """// <auto-generated>
//     Generated by tools/protocol/generate.py from obs-websocket {version}'s protocol definition
//     (tools/protocol/obs-websocket-protocol.json) and tools/protocol/overlay.toml.
//     Do not edit this file: change those inputs and run the generator again.
// </auto-generated>

#nullable enable
"""

CATEGORY_TITLES = {
    "general": "General",
    "config": "Config",
    "sources": "Sources",
    "scenes": "Scenes",
    "inputs": "Inputs",
    "transitions": "Transitions",
    "filters": "Filters",
    "scene items": "Scene Items",
    "outputs": "Outputs",
    "stream": "Stream",
    "record": "Record",
    "media inputs": "Media Inputs",
    "ui": "Ui",
    "canvases": "Canvases",
}

# The order of the protocol documentation. The protocol file lists the categories alphabetically; within a category
# the order of the protocol file is kept. A category that is not known here goes last.
CATEGORY_ORDER = list(CATEGORY_TITLES)


def by_category(items):
    rank = {category: index for index, category in enumerate(CATEGORY_ORDER)}
    return sorted(items, key=lambda item: rank.get(item.category, len(rank)))


# -- text helpers -----------------------------------------------------------------------------------------------------


def xml(text: str) -> str:
    """Protocol descriptions as XML documentation text: one line, escaped, `code` as <c>code</c>."""
    text = re.sub(r"\s+", " ", text.strip())
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return re.sub(r"`([^`]+)`", r"<c>\1</c>", text)


def sentence(text: str) -> str:
    text = text.strip()
    return text if not text or text[-1] in ".!?)" else text + "."


class Source:
    """Builds the text of one C# file, 4 spaces per level."""

    def __init__(self, model: Model, *, header: bool = True):
        self.lines: list[str] = []
        if header:
            self.lines += HEADER.format(version=model.version).splitlines()
            self.lines.append("")

    def add(self, depth: int = 0, text: str = "") -> None:
        self.lines.append(("    " * depth + text) if text else "")

    def summary(self, depth: int, text: str) -> None:
        self.add(depth, "/// <summary>")
        self.add(depth, "/// " + xml(text))
        self.add(depth, "/// </summary>")

    def text(self) -> str:
        return "\n".join(self.lines).rstrip("\n") + "\n"


def version_remark(since: str) -> str | None:
    return None if since == "5.0.0" else f"Introduced in obs-websocket {since}."


# -- DTOs -------------------------------------------------------------------------------------------------------------


def emit_dto(source: Source, dto: Dto, noun: str) -> None:
    users = [f"<c>{u}</c>" for u in dto.users]
    listed = users[0] if len(users) == 1 else ", ".join(users[:-1]) + " and " + users[-1]
    plural = "requests" if len(users) > 1 else "request"
    if noun == "response":
        summary = f"Provides the response data of the {listed} {plural}."
    else:
        plural = "events" if len(users) > 1 else "event"
        summary = f"Provides the arguments of the {listed} {plural}."

    ctor = ", ".join(f"{f.type.text} {pm.identifier(f.field.name)}" for f in dto.fields)
    source.add(1, "/// <summary>")
    source.add(1, "/// " + summary)
    source.add(1, "/// </summary>")
    source.add(1, "/// <remarks>")
    source.add(1, f'/// Initializes a new instance of the <see cref="{dto.name}"/> class.')
    remark = version_remark(dto.since)
    if remark:
        source.add(1, "/// " + remark)
    source.add(1, "/// </remarks>")
    for f in dto.fields:
        source.add(1, f'/// <param name="{pm.identifier(f.field.name)}">{xml(sentence(f.field.description))}</param>')
    source.add(1, "[method: JsonConstructor]")
    source.add(1, f"public class {dto.name}({ctor}) : {dto.base}")
    source.add(1, "{")
    for index, f in enumerate(dto.fields):
        if index:
            source.add()
        source.summary(2, sentence(f.field.description))
        source.add(2, f'[JsonPropertyName("{f.field.name}")]')
        if f.converter:
            source.add(2, f"[JsonConverter(typeof({f.converter}))]")
        initializer = pm.identifier(f.field.name)
        if f.type.is_collection and not f.type.nullable:
            initializer += " ?? []"
        source.add(2, f"public {f.type.text} {pm.pascal(f.field.name)} {{ get; }} = {initializer};")
    source.add(1, "}")


def emit_dtos(model: Model, namespace: str, dtos: list[Dto], noun: str) -> str:
    source = Source(model)
    source.add(0, f"namespace {namespace}")
    source.add(0, "{")
    for using in ("OBSStudioClient.Classes", "OBSStudioClient.Converters", "OBSStudioClient.Enums", "OBSStudioClient.Interfaces",
                  "System.Text.Json", "System.Text.Json.Serialization"):
        source.add(1, f"using {using};")
    for dto in dtos:
        source.add()
        emit_dto(source, dto, noun)
    source.add(0, "}")
    return source.text()


# -- registries -------------------------------------------------------------------------------------------------------


def emit_response_registry(model: Model) -> str:
    source = Source(model)
    source.add(0, "namespace OBSStudioClient.Messages")
    source.add(0, "{")
    source.add(1, "using OBSStudioClient.Enums;")
    source.add(1, "using OBSStudioClient.Responses;")
    source.add()
    source.add(1, "public partial class RequestResponseMessage")
    source.add(1, "{")
    source.add(2, "/// <summary>")
    source.add(2, "/// Gets the type of the response data of each request.")
    source.add(2, "/// </summary>")
    source.add(2, "private static readonly Dictionary<RequestType, Type> _responseTypeMap = new()")
    source.add(2, "{")
    category = None
    for request in by_category(model.requests):
        if request.category != category:
            if category is not None:
                source.add()
            category = request.category
            source.add(3, f"// {CATEGORY_TITLES.get(category, category.title())} requests")
        source.add(3, f"{{ RequestType.{request.name}, typeof({model.response_dto(request.name)}) }},")
    source.add(2, "};")
    source.add(1, "}")
    source.add(0, "}")
    return source.text()


def emit_event_registry(model: Model) -> str:
    source = Source(model)
    source.add(0, "namespace OBSStudioClient.Messages")
    source.add(0, "{")
    source.add(1, "using OBSStudioClient.Enums;")
    source.add(1, "using OBSStudioClient.Events;")
    source.add()
    source.add(1, "public partial class EventMessage")
    source.add(1, "{")
    source.add(2, "/// <summary>")
    source.add(2, "/// Gets the type of the arguments of each event.")
    source.add(2, "/// </summary>")
    source.add(2, "private static readonly Dictionary<EventType, Type> _responseTypeMap = new()")
    source.add(2, "{")
    source.add(3, "// Unknown: an event type this client version does not recognize yet. Treated as a no-data")
    source.add(3, "// event so it is safely ignored instead of throwing. See EventTypeConverter.")
    source.add(3, "{ EventType.Unknown, typeof(EventArgs) },")
    category = None
    for event in by_category(model.events):
        if event.category != category:
            category = event.category
            source.add()
            source.add(3, f"// {CATEGORY_TITLES.get(category, category.title())} events")
        dto = model.event_dto(event.name) or "EventArgs"
        source.add(3, f"{{ EventType.{event.name}, typeof({dto}) }},")
    source.add(2, "};")
    source.add(1, "}")
    source.add(0, "}")
    return source.text()


# -- events -----------------------------------------------------------------------------------------------------------


def emit_events(model: Model) -> str:
    source = Source(model)
    source.add(0, "namespace OBSStudioClient")
    source.add(0, "{")
    source.add(1, "using OBSStudioClient.Enums;")
    source.add(1, "using OBSStudioClient.Events;")
    source.add()
    source.add(0, "#pragma warning disable CS0067 // The event handlers are called through a MulticastDelegate, which is not detected by the compiler.")
    source.add(1, "public partial class ObsClient")
    source.add(1, "{")
    category = None
    first = True
    for event in by_category(model.events):
        if event.category != category:
            category = event.category
            if not first:
                source.add()
            first = False
            source.add(2, "//")
            source.add(2, f"// {CATEGORY_TITLES.get(category, category.title())} Events")
            source.add(2, "//")
        source.add()
        source.add(2, "/// <summary>")
        source.add(2, "/// " + xml(sentence(event.description)))
        source.add(2, "/// </summary>")
        remarks = [f"Needs the <see cref=\"EventSubscriptions.{event.subscription}\"/> event subscription."]
        remark = version_remark(event.since)
        if remark:
            remarks.append(remark)
        source.add(2, "/// <remarks>")
        for text in remarks:
            source.add(2, "/// " + text)
        source.add(2, "/// </remarks>")
        dto = model.event_dto(event.name)
        handler = f"EventHandler<{dto}>" if dto else "EventHandler"
        source.add(2, f"public event {handler}? {event.name};")
    source.add(1, "}")
    source.add(0, "#pragma warning restore CS0067")
    source.add(0, "}")
    return source.text()


# -- enums ------------------------------------------------------------------------------------------------------------


def emit_enum(model: Model, enum: str, members: list[tuple[str, int, str]], summary: str, converter: str) -> str:
    source = Source(model)
    source.add(0, "namespace OBSStudioClient.Enums")
    source.add(0, "{")
    if converter != "JsonStringEnumConverter":
        source.add(1, "using OBSStudioClient.Converters;")
    source.add(1, "using System.Text.Json.Serialization;")
    source.add()
    source.summary(1, summary)
    source.add(1, "/// <remarks>")
    source.add(1, "/// The numeric values of the members are not part of the obs-websocket protocol, but they are embedded in the assemblies")
    source.add(1, "/// that use this enum. A member keeps its value (they are listed in tools/protocol/overlay.toml); new members get the next number.")
    source.add(1, "/// </remarks>")
    source.add(1, f"[JsonConverter(typeof({converter}))]")
    source.add(1, f"public enum {enum}")
    source.add(1, "{")
    for index, (name, value, description) in enumerate(members):
        if index:
            source.add()
        if description:
            source.summary(2, description)
        source.add(2, f"{name} = {value},")
    source.add(1, "}")
    source.add(0, "}")
    return source.text()


def ordinal_members(model: Model, enum: str, known: dict[str, tuple[str, str]]) -> list[tuple[str, int, str]]:
    special = {
        "Unknown": "An event type that this version of the client does not recognize, for example one that obs-websocket "
                   "introduced after this client was released. No handler is invoked for it.",
    }
    ordinals = model.ordinals(enum)
    members = []
    for name, value in sorted(ordinals.items(), key=lambda item: (item[1] >= 0, item[1])):
        if name in special:
            members.append((name, value, special[name]))
            continue
        description, since = known.get(name, ("", ""))
        if not description:
            description = "No longer part of obs-websocket; kept so that the values of the other members do not change."
        remark = version_remark(since) if since else None
        members.append((name, value, sentence(description) + (" " + remark if remark else "")))
    return members


def unassigned_ordinals(model: Model) -> dict[str, list[str]]:
    result = {}
    for enum, names in (("RequestType", [r.name for r in model.requests]), ("EventType", [e.name for e in model.events])):
        known = model.ordinals(enum)
        missing = [n for n in names if n not in known]
        if missing:
            result[enum] = missing
    return result


def assign_ordinals(model: Model, missing: dict[str, list[str]]) -> None:
    """Appends the next numbers for new requests and events to the [ordinals.*] tables of overlay.toml."""
    text = pm.OVERLAY_FILE.read_text(encoding="utf-8")
    for enum, names in missing.items():
        ordinals = model.ordinals(enum)
        next_value = max(ordinals.values()) + 1
        lines = text.split("\n")
        header = lines.index(f"[ordinals.{enum}]")
        end = header + 1
        while end < len(lines) and not lines[end].startswith("["):
            end += 1
        while lines[end - 1].strip() == "":
            end -= 1
        for offset, name in enumerate(names):
            lines.insert(end + offset, f"{name} = {next_value + offset}")
        text = "\n".join(lines)
        print(f"  assigned {enum} ordinals: " + ", ".join(f"{n} = {next_value + i}" for i, n in enumerate(names)))
    pm.OVERLAY_FILE.write_text(text, encoding="utf-8", newline="\n")


# -- snapshot for the tests -------------------------------------------------------------------------------------------


def evaluate_enum_value(value, resolved):
    """Turns an upstream enumValue (an int, "-1", "(1 << 4)" or "(A | B)") into an int; anything else stays text."""
    if isinstance(value, int):
        return value
    text = str(value).strip()
    if re.fullmatch(r"-?\d+", text):
        return int(text)
    shift = re.fullmatch(r"\(?\s*(\d+)\s*<<\s*(\d+)\s*\)?", text)
    if shift:
        return int(shift.group(1)) << int(shift.group(2))
    if "|" in text:
        total = 0
        for part in text.strip("() ").split("|"):
            name = part.strip()
            if name not in resolved or not isinstance(resolved[name], int):
                return text
            total |= resolved[name]
        return total
    return text


def snapshot_field(f: pm.Field) -> dict:
    result = {"name": f.name, "type": f.vtype}
    if f.optional:
        result["optional"] = True
    return result


def build_snapshot(model: Model) -> dict:
    enums = {}
    for enum in sorted(model.enums, key=lambda e: e["enumType"]):
        resolved = {}
        for identifier in enum["enumIdentifiers"]:
            resolved[identifier["enumIdentifier"]] = evaluate_enum_value(identifier.get("enumValue"), resolved)
        enums[enum["enumType"]] = resolved
    return {
        "obsWebSocketVersion": model.version,
        "source": f"https://github.com/obsproject/obs-websocket/blob/{model.version}/docs/generated/protocol.json",
        "requests": {
            r.name: {"request": [snapshot_field(f) for f in r.request_fields], "response": [snapshot_field(f) for f in r.response_fields]}
            for r in sorted(model.requests, key=lambda r: r.name)
        },
        "events": {e.name: [snapshot_field(f) for f in e.fields] for e in sorted(model.events, key=lambda e: e.name)},
        "enums": enums,
    }


# -- orchestration ----------------------------------------------------------------------------------------------------


def generate(model: Model) -> dict[Path, str]:
    """Every file the generator owns, by path."""
    files: dict[Path, str] = {}
    descriptions = {r.name: (r.description, r.since) for r in model.requests}
    event_descriptions = {e.name: (e.description, e.since) for e in model.events}

    files[GENERATED / "Responses.g.cs"] = emit_dtos(model, "OBSStudioClient.Responses", pm.response_dtos(model), "response")
    files[GENERATED / "EventArgs.g.cs"] = emit_dtos(model, "OBSStudioClient.Events", pm.event_dtos(model), "event")
    files[GENERATED / "RequestResponseMessage.g.cs"] = emit_response_registry(model)
    files[GENERATED / "EventMessage.g.cs"] = emit_event_registry(model)
    files[GENERATED / "ObsClient.Events.g.cs"] = emit_events(model)
    files[GENERATED / "RequestType.g.cs"] = emit_enum(
        model, "RequestType", ordinal_members(model, "RequestType", descriptions),
        "The requests that obs-websocket knows.", "JsonStringEnumConverter")
    files[GENERATED / "EventType.g.cs"] = emit_enum(
        model, "EventType", ordinal_members(model, "EventType", event_descriptions),
        "The events that obs-websocket knows. Unknown stands for an event type this version of the client does not know.", "EventTypeConverter")
    files[SNAPSHOT] = json.dumps(build_snapshot(model), indent=2) + "\n"
    return files


def existing_generated_files() -> set[Path]:
    return set(GENERATED.glob("*.g.cs")) if GENERATED.is_dir() else set()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the committed files differ from what would be generated")
    parser.add_argument("--output-root", help="write below this directory instead of the repository (for experiments)")
    args = parser.parse_args(argv)

    try:
        model = Model.load()
        missing = unassigned_ordinals(model)
        if missing:
            if args.check:
                for enum, names in missing.items():
                    print(f"::error::{enum} has no ordinal for {', '.join(names)}; run tools/protocol/generate.py and commit overlay.toml")
                return 1
            assign_ordinals(model, missing)
            model = Model.load()
        files = generate(model)
    except ModelError as error:
        print(f"::error::{error}")
        return 1

    if args.output_root:
        root = Path(args.output_root)
        files = {root / path.relative_to(pm.ROOT): content for path, content in files.items()}

    if args.check:
        problems = []
        for path, content in sorted(files.items()):
            if not path.exists():
                problems.append(f"{path.relative_to(pm.ROOT)} is missing")
            elif path.read_bytes() != content.encode("utf-8"):
                problems.append(f"{path.relative_to(pm.ROOT)} is not what the generator produces")
        stale = sorted(existing_generated_files() - set(files))
        problems += [f"{path.relative_to(pm.ROOT)} is no longer generated" for path in stale]
        if problems:
            for problem in problems:
                print(f"::error::{problem}")
            print("Run `python tools/protocol/generate.py` and commit the result.")
            return 1
        print(f"The {len(files)} generated files are up to date.")
        return 0

    for path, content in sorted(files.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode("utf-8"))
    if not args.output_root:
        for path in sorted(existing_generated_files() - set(files)):
            path.unlink()
            print(f"removed {path.relative_to(pm.ROOT)} (no longer generated)")
    print(f"Wrote {len(files)} files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
